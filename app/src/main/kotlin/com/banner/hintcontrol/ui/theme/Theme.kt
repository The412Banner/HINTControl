@Immutable
data class QualityColors(
    val excellent: Color,
    val good: Color,
    val fair: Color,
    val poor: Color,
    val unknown: Color,
) {
    fun of(q: Quality?): Color = when (q) {
        Quality.Excellent -> excellent
        Quality.Good -> good
        Quality.Fair -> fair
        Quality.Poor -> poor
        null -> unknown
    }
}

